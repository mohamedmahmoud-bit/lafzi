/** Minimal RFC 4180 CSV parser (quotes, escaped quotes, CRLF, BOM). Preserves Arabic Unicode. */
export function parseCsv(text: string): string[][] {
  const src = text.replace(/^﻿/, "");
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"' && src[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      if (row.some((f) => f.trim() !== "")) rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  row.push(field);
  if (row.some((f) => f.trim() !== "")) rows.push(row);
  return rows;
}

/** Split a multi-value cell: "شجاع|مقدام" or "شجاع، مقدام" or "شجاع؛ مقدام". */
export function splitList(cell: string | undefined): string[] {
  return (cell ?? "")
    .split(/[|،؛;]/)
    .map((s) => s.trim())
    .filter(Boolean);
}
